#!/usr/bin/env bash
# ---------------------------------------------------------------------------
# chrome-mcp-launch.sh — per-workspace launcher for chrome-devtools-mcp.
#
# Register ONCE at user scope so every project inherits it:
#     claude mcp add chrome -s user -- <path-to-this-file>
#
# WHY A LAUNCHER: Claude Code spawns an MCP server with cwd = the directory you
# started `claude` in. Git worktrees collapse to their MAIN repo for config
# lookup (so a per-worktree `claude mcp add` can't isolate them — they overwrite
# each other), but the SPAWN cwd is the real worktree. So instead of registering
# a server per workspace, we register ONE global server that reads $PWD at launch
# to tell which workspace it's in, and hands Chrome a per-workspace persistent
# user-data-dir. Result: one isolated browser per workspace, logins preserved,
# from a single registration — and the profile is chosen by WHERE you run
# `claude`, nothing for the agent to pick. Outside a workspace it falls back to a
# shared default profile.
#
# Flags:
#   --print-profile   print the resolved slug + profile dir, then exit (testing)
# Any other args are passed through to chrome-devtools-mcp.
#
# Env:
#   CHROME_MCP_PROFILE_ROOT   override the profiles dir (default ~/.chrome-mcp)
#   WSM_CONFIG                 explicit config path (else <repo>/config.sh)
# ---------------------------------------------------------------------------
set -uo pipefail

PROFILE_ROOT="${CHROME_MCP_PROFILE_ROOT:-$HOME/.chrome-mcp}"

# Resolve this script's real repo home (follow symlinks), like the `workspaces`
# entrypoint, so a PATH symlink still finds config.sh.
_src="${BASH_SOURCE[0]}"
while [[ -h "$_src" ]]; do
  _dir="$(cd -P "$(dirname "$_src")" && pwd)"
  _src="$(readlink "$_src")"
  [[ "$_src" != /* ]] && _src="$_dir/$_src"
done
WSM_HOME="$(cd -P "$(dirname "$_src")/.." && pwd)"

# Best-effort: read WORKSPACES_ROOT from the config so slug detection matches the
# tool exactly. Sourced in a subshell so it can never disturb this process; a
# missing/broken config just leaves it empty and we use the generic match below.
WORKSPACES_ROOT=""
_cfg="${WSM_CONFIG:-$WSM_HOME/config.sh}"
if [[ -f "$_cfg" ]]; then
  # shellcheck source=/dev/null
  WORKSPACES_ROOT="$( source "$_cfg" 2>/dev/null; printf '%s' "${WORKSPACES_ROOT:-}" )"
fi

# Derive the workspace slug from the launch cwd: the path component directly
# under WORKSPACES_ROOT (or under a generic ".../workspaces/" if no config).
# Use the REAL cwd (pwd -P), never $PWD — a launcher spawned by an IDE can
# inherit a stale $PWD env var pointing at a different window's directory, which
# would hand this workspace the wrong profile.
cwd="$(pwd -P 2>/dev/null || printf '%s' "$PWD")"
slug=""
wsdir=""
if [[ -n "$WORKSPACES_ROOT" && "$cwd" == "$WORKSPACES_ROOT/"* ]]; then
  rel="${cwd#"$WORKSPACES_ROOT"/}"; slug="${rel%%/*}"
  wsdir="$WORKSPACES_ROOT/$slug"
elif [[ "$cwd" == */workspaces/* ]]; then
  rel="${cwd#*/workspaces/}"; slug="${rel%%/*}"
  wsdir="${cwd%%/workspaces/*}/workspaces/$slug"
fi

profile_dir="$PROFILE_ROOT/${slug:-_default}"

# Tint the browser to the workspace's accent color — the same hex ws list and
# the VS Code title bar use (titleBar.activeBackground in the .code-workspace),
# so each workspace's Chrome window is recognisable at a glance. Chrome's
# --install-autogenerated-theme builds a theme from an R,G,B seed and, unlike a
# packed theme, survives the automation launch's --disable-extensions.
theme_arg=""
if [[ -n "$wsdir" ]]; then
  wsfile="$wsdir/$slug.code-workspace"
  [[ -f "$wsfile" ]] || wsfile="$(ls "$wsdir"/*.code-workspace 2>/dev/null | head -1)"
  if [[ -n "${wsfile:-}" && -f "$wsfile" ]]; then
    hex="$(grep -o '"titleBar\.activeBackground"[[:space:]]*:[[:space:]]*"#[0-9a-fA-F]\{6\}"' \
             "$wsfile" 2>/dev/null | grep -o '#[0-9a-fA-F]\{6\}' | head -1)"
    if [[ "$hex" =~ ^#[0-9a-fA-F]{6}$ ]]; then
      h="${hex#\#}"
      theme_arg="--chromeArg=--install-autogenerated-theme=$((16#${h:0:2})),$((16#${h:2:2})),$((16#${h:4:2}))"
    fi
  fi
fi

if [[ "${1:-}" == "--print-profile" ]]; then
  printf 'slug=%s\nprofile=%s\ntheme=%s\n' "${slug:-<none>}" "$profile_dir" "${theme_arg:-<none>}"
  exit 0
fi

mkdir -p "$profile_dir"

# Hand off to the real server. exec so Chrome's lifecycle is owned by the MCP
# server process Claude manages (starts lazily on first tool call, closes on
# session end) — no extra process to track. theme_arg is omitted entirely when
# there's no workspace color to apply (e.g. the _default fallback).
exec npx -y chrome-devtools-mcp@latest \
  --userDataDir "$profile_dir" \
  --acceptInsecureCerts \
  ${theme_arg:+"$theme_arg"} \
  "$@"
